const (
	setupEnvFile     = ".env"
	setupKeyFile     = "github-app.pem"
	setupPendingFile = ".runquill-setup.pending"
	setupEnvHeader   = "# Generated by runquill setup.\n"
)

// Set by the release build so a first-time user gets both matching image tags.
var releaseImage string

var setupLogin = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9-]{0,38}$`)
var setupImage = regexp.MustCompile(`^[a-z0-9][a-z0-9./_-]*:[a-zA-Z0-9_][a-zA-Z0-9_.-]*$`)
var setupSecret = regexp.MustCompile(`^[a-zA-Z0-9_-]{16,256}$`)

type setupOptions struct {
	webhookURL string
	port       int
}

func (opts setupOptions) validate() error {
	if opts.port < 0 || opts.port > 65535 {
		return errors.New("listen port must be between 0 and 65535")
	}
	if opts.webhookURL == "" {
		return nil
	}
	endpoint, err := url.Parse(opts.webhookURL)
	if err != nil || endpoint.Scheme != "https" || endpoint.Hostname() == "" || endpoint.User != nil ||
		endpoint.EscapedPath() != "/webhook" || endpoint.RawQuery != "" || endpoint.ForceQuery ||
		strings.ContainsAny(opts.webhookURL, "#$'\"") {
		return errors.New("webhook URL must be an HTTPS URL ending in /webhook without credentials, query, or fragment")
	}
	return nil
}

type pendingSetup struct {
	Env string
	PEM string
}

func setup(ctx context.Context, out io.Writer, dir string, client *http.Client, apiBase string, opts setupOptions) error {
	if err := opts.validate(); err != nil {
		return err
	}
	lock, err := os.OpenFile(filepath.Join(dir, ".runquill-setup.lock"), os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return fmt.Errorf("open setup lock: %w", err)
	}
	defer lock.Close()
	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		return fmt.Errorf("lock setup directory: %w", err)
	}

	envData, err := setupFiles(ctx, out, dir, client, apiBase, opts)
	if err != nil {
		return err
	}
	values, err := setupValues(envData)
	if err != nil {
		return err
	}
	if opts.webhookURL != "" && values["RUNQUILL_WEBHOOK_URL"] != opts.webhookURL {
		return errors.New("this directory has an App configuration with a different webhook URL; update the existing App or use a new directory")
	}
	keyPath := values["RUNQUILL_KEY_FILE"]
	if !filepath.IsAbs(keyPath) {
		keyPath = filepath.Join(dir, keyPath)
	}
	keyData, err := os.ReadFile(keyPath)
	if err != nil {
		return fmt.Errorf("read setup key: %w", err)
	}
	key, err := parseKey(keyData)
	if err != nil {
		return fmt.Errorf("parse setup key: %w", err)
	}
	api := &github{client: client, base: apiBase, appID: values["RUNQUILL_APP_ID"], owner: values["RUNQUILL_OWNER"], key: key}
	fmt.Fprintf(out, "Configuration ready for %s in %s.\n", api.owner, filepath.Join(dir, setupEnvFile))
	if err := waitForSetupInstallation(ctx, out, api); err != nil {
		return fmt.Errorf("check GitHub App installation (rerun runquill setup to resume): %w", err)
	}

	fmt.Fprintln(out, "GitHub App installed with access to all repositories. Run these commands from the Runquill project directory:")
	if runner := values["RUNQUILL_RUNNER_IMAGE"]; setupImage.MatchString(runner) && setupImage.MatchString(values["RUNQUILL_MANAGER_IMAGE"]) {
		fmt.Fprintf(out, "  docker pull %s\n  docker compose pull manager\n  docker compose up -d --no-build\n", runner)
	} else {
		fmt.Fprintln(out, "  docker build --pull -t runquill-runner:local runner")
		fmt.Fprintln(out, "  docker compose up -d --build")
	}
	fmt.Fprintln(out, "  docker compose exec manager runquill doctor")
	if endpoint := values["RUNQUILL_WEBHOOK_URL"]; endpoint != "" {
		fmt.Fprintf(out, "Forward %s to http://127.0.0.1:8080/webhook with your HTTPS reverse proxy.\n", endpoint)
	}
	fmt.Fprintln(out, "Run examples/runquill-smoke.yml in a private repository to verify runner assignment and cleanup.")
	return nil
}

func setupFiles(ctx context.Context, out io.Writer, dir string, client *http.Client, apiBase string, opts setupOptions) ([]byte, error) {
	envPath := filepath.Join(dir, setupEnvFile)
	keyPath := filepath.Join(dir, setupKeyFile)
	pendingPath := filepath.Join(dir, setupPendingFile)
	var pending pendingSetup
	newApp := false
	info, err := os.Lstat(pendingPath)
	switch {
	case err == nil:
		if !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 {
			return nil, fmt.Errorf("setup recovery data must be a private regular file: %s", pendingPath)
		}
		data, err := os.ReadFile(pendingPath)
		if err != nil {
			return nil, err
		}
		if err := json.Unmarshal(data, &pending); err != nil {
			return nil, fmt.Errorf("read setup recovery data: %w", err)
		}
	case errors.Is(err, os.ErrNotExist):
		data, err := os.ReadFile(envPath)
		if err == nil {
			return data, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		for _, path := range []string{envPath, keyPath} {
			if _, err := os.Lstat(path); err == nil {
				return nil, fmt.Errorf("%s already exists; preserve it and use the manual setup instructions", path)
			} else if !errors.Is(err, os.ErrNotExist) {
				return nil, err
			}
		}
		app, err := registerManifestApp(ctx, out, client, apiBase, opts)
		if err != nil {
			return nil, err
		}
		if app.ID <= 0 || app.Owner.Type != "User" || !setupLogin.MatchString(app.Owner.Login) {
			return nil, errors.New("GitHub did not return an App registered to a personal account")
		}
		pending = pendingSetup{
			Env: setupEnvironment(app.Owner.Login, app.ID, releaseImage, version),
			PEM: app.PEM,
		}
		if opts.webhookURL != "" {
			if !setupSecret.MatchString(app.WebhookSecret) {
				return nil, errors.New("GitHub did not return a usable webhook secret")
			}
			pending.Env += fmt.Sprintf("RUNQUILL_WEBHOOK_URL=%s\nRUNQUILL_WEBHOOK_SECRET=%s\nRUNQUILL_POLL_INTERVAL=30s\n", opts.webhookURL, app.WebhookSecret)
		}
		newApp = true
	default:
		return nil, err
	}
	if _, err := setupValues([]byte(pending.Env)); err != nil {
		return nil, err
	}
	if _, err := parseKey([]byte(pending.PEM)); err != nil {
		return nil, fmt.Errorf("parse GitHub App key: %w", err)
	}
	if newApp {
		data, err := json.Marshal(pending)
		if err != nil {
			return nil, err
		}
		if err := writeSetupFile(pendingPath, data); err != nil {
			return nil, fmt.Errorf("save setup recovery data: %w", err)
		}
	}
	if err := saveSetupFile(keyPath, []byte(pending.PEM)); err != nil {
		return nil, err
	}
	if err := saveSetupFile(envPath, []byte(pending.Env)); err != nil {
		return nil, err
	}
	if err := os.Remove(pendingPath); err != nil {
		return nil, fmt.Errorf("remove setup recovery data: %w", err)
	}
	return []byte(pending.Env), nil
}

func setupEnvironment(owner string, appID int64, image, tag string) string {
	env := fmt.Sprintf("%sRUNQUILL_OWNER=%s\nRUNQUILL_APP_ID=%d\nRUNQUILL_KEY_FILE=./%s\n", setupEnvHeader, owner, appID, setupKeyFile)
	if image != "" && setupImage.MatchString(image+":"+tag) {
		env += fmt.Sprintf("RUNQUILL_MANAGER_IMAGE=%s:%s\nRUNQUILL_RUNNER_IMAGE=%s-runner:%s\n", image, tag, image, tag)
	}
	return env
}

func setupValues(data []byte) (map[string]string, error) {
	content, generated := strings.CutPrefix(string(data), setupEnvHeader)
	if !generated {
		return nil, errors.New(".env already exists with manual configuration; use docker compose exec manager runquill doctor to check it")
	}
	values := make(map[string]string)
	for line := range strings.SplitSeq(content, "\n") {
		key, value, ok := strings.Cut(line, "=")
		if ok {
			values[strings.TrimSpace(key)] = strings.TrimSpace(value)
		}
	}
	id, err := strconv.ParseInt(values["RUNQUILL_APP_ID"], 10, 64)
	if err != nil || id <= 0 || !setupLogin.MatchString(values["RUNQUILL_OWNER"]) || values["RUNQUILL_KEY_FILE"] == "" {
		return nil, errors.New("generated .env has missing or invalid GitHub App settings")
	}
	return values, nil
}

func saveSetupFile(path string, data []byte) error {
	err := writeSetupFile(path, data)
	if errors.Is(err, os.ErrExist) {
		existing, readErr := os.ReadFile(path)
		if readErr == nil && bytes.Equal(existing, data) {
			info, statErr := os.Lstat(path)
			if statErr == nil && info.Mode().IsRegular() && info.Mode().Perm()&0077 == 0 {
				return nil
			}
		}
		return fmt.Errorf("%s already exists; setup kept it and preserved the new credentials in %s", path, setupPendingFile)
	}
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func writeSetupFile(path string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(path), ".runquill-setup-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Sync(); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Link(file.Name(), path)
}

func waitForSetupInstallation(ctx context.Context, out io.Writer, api *github) error {
	ctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
	defer cancel()
	instructionsShown := false
	for {
		jwt, err := api.jwt(time.Now())
		if err != nil {
			return err
		}
		inst, err := api.installation(ctx, jwt)
		if err == nil {
			err := errors.Join(inst.accessErrors())
			if err != nil {
				fmt.Fprintf(out, "Review the App installation at https://github.com/settings/installations/%d\n", inst.ID)
			}
			return err
		}
		if !githubNotFound(err) {
			return err
		}
		if !instructionsShown {
			var app struct{ Slug string }
			if err := api.request(ctx, http.MethodGet, "/app", jwt, nil, &app); err != nil {
				return err
			}
			if app.Slug == "" {
				return errors.New("GitHub did not return an App slug")
			}
			fmt.Fprintf(out, "Install the App on %s and select All repositories:\n  https://github.com/apps/%s/installations/new\n", api.owner, url.PathEscape(app.Slug))
			fmt.Fprintln(out, "Waiting for installation. You can rerun setup to resume.")
			instructionsShown = true
		}
		timer := time.NewTimer(3 * time.Second)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
	}
}
