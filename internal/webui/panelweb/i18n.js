function preferredLanguage() {
  const requested = new URL(location.href).searchParams.get("lang");
  try {
    if (requested === "ko" || requested === "en") localStorage.setItem("runquill-language", requested);
    return localStorage.getItem("runquill-language") || (navigator.language.startsWith("ko") ? "ko" : "en");
  } catch {
    return requested === "ko" || requested === "en" ? requested : "en";
  }
}

export const language = preferredLanguage();

export function tr(message, values = {}) {
  const translated = language === "ko" && Object.hasOwn(words, message) ? words[message] : message;
  return String(translated).replace(/\{([a-z]+)\}/g, (token, key) => Object.hasOwn(values, key) ? values[key] : token);
}

// Server messages are a stable English sentence that is a key above. Dynamic
// details either follow it on later lines, shown verbatim, or match a
// template in serverPatterns. Anything else is shown as the server sent it.
export function serverText(message) {
  const text = String(message || "").trim();
  const [head, ...detail] = text.split("\n");
  if (Object.hasOwn(words, head)) return [tr(head), ...detail].join("\n");
  if (language !== "ko") return text;
  for (const { key, names, pattern } of serverPatterns) {
    const match = pattern.exec(text);
    if (!match) continue;
    const values = Object.fromEntries(names.map((name, i) => [name, name === "detail" ? serverText(match[i + 1]) : match[i + 1]]));
    return tr(key, values);
  }
  return text;
}

// localizeDocument translates the static shell in index.html. Views translate
// their own text with tr() as they build it.
export function localizeDocument() {
  document.documentElement.lang = language;
  const alternate = language === "ko" ? "en" : "ko";
  const target = new URL(location.href);
  target.searchParams.set("lang", alternate);
  for (const toggle of document.querySelectorAll(".language-toggle")) {
    toggle.href = target;
    toggle.textContent = alternate === "en" ? "English" : "한국어";
    toggle.lang = alternate;
  }
  if (language !== "ko") return;
  const fragments = [...document.querySelectorAll("template")].map((element) => element.content);
  for (const area of [document.body, ...fragments]) {
    const tree = document.createTreeWalker(area, NodeFilter.SHOW_TEXT);
    for (let part = tree.nextNode(); part; part = tree.nextNode()) {
      const content = part.nodeValue.trim();
      if (Object.hasOwn(words, content)) part.nodeValue = part.nodeValue.replace(content, words[content]);
    }
    for (const node of area.querySelectorAll("[aria-label], [placeholder]")) {
      for (const attr of ["aria-label", "placeholder"]) {
        if (node.hasAttribute(attr)) node.setAttribute(attr, tr(node.getAttribute(attr)));
      }
    }
  }
}
