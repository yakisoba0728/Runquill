const (
	setupEnvFile     = ".env"
	setupKeyFile     = "github-app.pem"
	setupPendingFile = ".runquill-setup.pending"
	setupEnvHeader   = "# Generated by runquill setup.\n"
)

// Set by the release build so a first-time user gets both matching image tags.
var releaseImage string

var setupLogin = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9-]{0,38}$`)
var setupImage = regexp.MustCompile(`^[a-z0-9][a-z0-9./_-]*:[a-zA-Z0-9_][a-zA-Z0-9_.-]*$`)
var setupSecret = regexp.MustCompile(`^[a-zA-Z0-9_-]{16,256}$`)

type setupOptions struct {
	webhookURL      string
	port            int
	kubernetes      bool
	panel           bool
	panelURL        string
	repositoryScope string
	organization    string
	runnerGroupID   int64
}

func (opts setupOptions) validate() error {
	if opts.organization != "" && !setupLogin.MatchString(opts.organization) {
		return errors.New("--organization must be a GitHub organization login")
	}
	if opts.runnerGroupID < 0 || opts.runnerGroupID > 0 && opts.organization == "" {
		return errors.New("--runner-group-id must be a positive integer and requires --organization")
	}
	if _, err := parseRepositoryScope(opts.repositoryScope); err != nil {
		return fmt.Errorf("--repository-scope: %w", err)
	}
	if opts.port < 0 || opts.port > 65535 {
		return errors.New("listen port must be between 0 and 65535")
	}
	if opts.panelURL != "" {
		if !opts.panel {
			return errors.New("--panel-url requires --panel")
		}
		if _, err := parsePanelURL(opts.panelURL); err != nil {
			return fmt.Errorf("--panel-url: %w", err)
		}
	}
	if opts.webhookURL == "" {
		return nil
	}
	endpoint, err := url.Parse(opts.webhookURL)
	if err != nil || endpoint.Scheme != "https" || endpoint.Hostname() == "" || endpoint.User != nil ||
		endpoint.EscapedPath() != "/webhook" || endpoint.RawQuery != "" || endpoint.ForceQuery ||
		strings.ContainsAny(opts.webhookURL, "#$'\"") {
		return errors.New("webhook URL must be an HTTPS URL ending in /webhook without credentials, query, or fragment")
	}
	return nil
}

type pendingSetup struct {
	Env string
	PEM string
}

func setup(ctx context.Context, out io.Writer, dir string, client *http.Client, apiBase string, opts setupOptions) error {
	if err := opts.validate(); err != nil {
		return err
	}
	lock, err := os.OpenFile(filepath.Join(dir, ".runquill-setup.lock"), os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return fmt.Errorf("open setup lock: %w", err)
	}
	defer lock.Close()
	if err := lockExclusive(lock); err != nil {
		return fmt.Errorf("lock setup directory: %w", err)
	}
	web := currentWizard(ctx)
	if web != nil {
		cleanup := web.prepareNetwork(ctx, &opts)
		defer cleanup()
	}

	envData, err := setupFiles(ctx, out, dir, client, apiBase, opts)
	if err != nil {
		return err
	}
	values, err := setupValues(envData)
	if err != nil {
		return err
	}
	if opts.webhookURL != "" && values["RUNQUILL_WEBHOOK_URL"] != opts.webhookURL {
		return errors.New("this directory has an App configuration with a different webhook URL; update the existing App or use a new directory")
	}
	scope, err := parseRepositoryScope(values[repositoryScopeEnv])
	if err != nil {
		return fmt.Errorf("%s: %w", repositoryScopeEnv, err)
	}
	if opts.repositoryScope != "" && opts.repositoryScope != scope {
		return fmt.Errorf("this directory is configured for %s. Change the App installation and update %s to switch this installation",
			repositoryScopeLabel(scope), repositoryScopeEnv)
	}
	organization, group, err := parseGitHubTarget(values[ownerTypeEnv], values[runnerGroupEnv])
	if err != nil {
		return err
	}
	if opts.organization != "" && (!organization || !strings.EqualFold(opts.organization, values["RUNQUILL_OWNER"])) {
		return errors.New("this directory is configured for a different GitHub account; use a new directory")
	}
	if opts.runnerGroupID > 0 && opts.runnerGroupID != group {
		return fmt.Errorf("this directory uses a different runner group; review %s and your GitHub App permissions", runnerGroupEnv)
	}
	allowPublic, err := parseAllowPublic(values[allowPublicEnv])
	if err != nil {
		return err
	}
	keyPath := values["RUNQUILL_KEY_FILE"]
	if !filepath.IsAbs(keyPath) {
		keyPath = filepath.Join(dir, keyPath)
	}
	keyData, err := os.ReadFile(keyPath)
	if err != nil {
		return fmt.Errorf("read setup key: %w", err)
	}
	key, err := parseKey(keyData)
	if err != nil {
		return fmt.Errorf("parse setup key: %w", err)
	}
	api := &github{client: client, base: apiBase, appID: values["RUNQUILL_APP_ID"], owner: values["RUNQUILL_OWNER"], key: key, repositoryScope: scope, organization: organization, runnerGroupID: group, allowPublic: allowPublic}
	fmt.Fprintf(out, "Configuration ready for %s in %s.\n", api.owner, filepath.Join(dir, setupEnvFile))
	installation, err := waitForSetupInstallation(ctx, out, api)
	if err != nil {
		return fmt.Errorf("check GitHub App installation (rerun runquill setup to resume): %w", err)
	}
	fmt.Fprintf(out, "GitHub App installed with %s access.\n", repositoryScopeLabel(scope))
	var panel panelOAuthConfig
	if opts.panel {
		adminID := installation.Account.ID
		if organization {
			adminID = 0 // An organization ID cannot sign in to the panel.
		}
		panel, err = configurePanelSetup(ctx, out, filepath.Join(dir, setupEnvFile), envData, values, opts, adminID)
		if err != nil {
			return fmt.Errorf("configure panel (rerun runquill setup --panel to resume): %w", err)
		}
		fmt.Fprintln(out, "Panel settings saved in .env.")
	}

	if web != nil {
		return nil
	}
	if opts.kubernetes {
		if err := saveSetupEnv(dir, "RUNQUILL_BACKEND", "kubernetes"); err != nil {
			return err
		}
		fmt.Fprintln(out, "Apply runquill-k3s.yaml to the intended Kubernetes context.")
		fmt.Fprintln(out, "  kubectl apply -f runquill-k3s.yaml")
		fmt.Fprintln(out, "  kubectl -n runquill-system create secret generic runquill-config --from-env-file=.env")
		fmt.Fprintln(out, "  kubectl -n runquill-system create secret generic runquill-github-key --from-file=github-app.pem")
		fmt.Fprintln(out, "  kubectl -n runquill-system rollout status deployment/runquill")
		fmt.Fprintln(out, "  kubectl -n runquill-system exec deployment/runquill -- runquill doctor")
		if opts.panel {
			fmt.Fprintln(out, "  kubectl -n runquill-system port-forward svc/runquill 8081:8081")
			printPanelSetupNext(out, panel, opts.kubernetes)
		}
		if endpoint := values["RUNQUILL_WEBHOOK_URL"]; endpoint != "" {
			fmt.Fprintf(out, "Route %s to /webhook on the runquill Service's port 8080.\n", endpoint)
		}
		fmt.Fprintln(out, "From the root of a private repository checkout, use runquill workflow init to create a first-job workflow.")
		return nil
	}

	values, err = readSetupEnv(dir)
	if err != nil {
		return err
	}
	if _, err := recordComposeFiles(dir, setupComposeFiles(values, opts.panel)); err != nil {
		return err
	}
	fmt.Fprintln(out, "Run these commands from the Runquill project directory (Compose reads its files from COMPOSE_FILE in .env):")
	compose := "docker compose"
	if runner := values["RUNQUILL_RUNNER_IMAGE"]; setupImage.MatchString(runner) && setupImage.MatchString(values["RUNQUILL_MANAGER_IMAGE"]) {
		fmt.Fprintf(out, "  docker pull %s\n  %s pull manager\n  %s up -d --no-build\n", runner, compose, compose)
	} else {
		fmt.Fprintln(out, "  docker build --pull -t runquill-runner:local runner")
		fmt.Fprintf(out, "  %s up -d --build\n", compose)
	}
	fmt.Fprintf(out, "  %s exec manager runquill doctor\n", compose)
	if opts.panel {
		printPanelSetupNext(out, panel, opts.kubernetes)
	}
	if endpoint := values["RUNQUILL_WEBHOOK_URL"]; endpoint != "" {
		fmt.Fprintf(out, "Forward %s to http://127.0.0.1:8080/webhook with your HTTPS reverse proxy.\n", endpoint)
	}
	fmt.Fprintln(out, "From the root of a private repository checkout, use runquill workflow init to create a first-job workflow.")
	return nil
}

func setupFiles(ctx context.Context, out io.Writer, dir string, client *http.Client, apiBase string, opts setupOptions) ([]byte, error) {
	envPath := filepath.Join(dir, setupEnvFile)
	keyPath := filepath.Join(dir, setupKeyFile)
	pendingPath := filepath.Join(dir, setupPendingFile)
	var pending pendingSetup
	newApp := false
	info, err := os.Lstat(pendingPath)
	switch {
	case err == nil:
		if !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 {
			return nil, fmt.Errorf("setup recovery data must be a private regular file: %s", pendingPath)
		}
		data, err := os.ReadFile(pendingPath)
		if err != nil {
			return nil, err
		}
		if err := json.Unmarshal(data, &pending); err != nil {
			return nil, fmt.Errorf("read setup recovery data: %w", err)
		}
	case errors.Is(err, os.ErrNotExist):
		data, err := os.ReadFile(envPath)
		if err == nil {
			return data, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		for _, path := range []string{envPath, keyPath} {
			if _, err := os.Lstat(path); err == nil {
				return nil, fmt.Errorf("%s already exists; preserve it and use the manual setup instructions", path)
			} else if !errors.Is(err, os.ErrNotExist) {
				return nil, err
			}
		}
		app, err := registerManifestApp(ctx, out, client, apiBase, opts)
		if err != nil {
			return nil, err
		}
		pending = pendingSetup{
			Env: setupEnvironment(app.Owner.Login, app.ID, releaseImage, version),
			PEM: app.PEM,
		}
		if opts.organization != "" {
			pending.Env += fmt.Sprintf("%s=%s\n", ownerTypeEnv, organizationOwnerType)
		}
		if opts.runnerGroupID > 0 {
			pending.Env += fmt.Sprintf("%s=%d\n", runnerGroupEnv, opts.runnerGroupID)
		}
		if opts.repositoryScope != "" {
			pending.Env += fmt.Sprintf("%s=%s\n", repositoryScopeEnv, opts.repositoryScope)
		}
		if opts.webhookURL != "" {
			if !setupSecret.MatchString(app.WebhookSecret) {
				return nil, errors.New("GitHub did not return a usable webhook secret")
			}
			pending.Env += fmt.Sprintf("RUNQUILL_WEBHOOK_URL=%s\nRUNQUILL_WEBHOOK_SECRET=%s\nRUNQUILL_POLL_INTERVAL=30s\n", opts.webhookURL, app.WebhookSecret)
		}
		if opts.panel {
			origin, err := setupPanelOrigin(opts.panelURL)
			if err != nil {
				return nil, err
			}
			pending.Env += fmt.Sprintf("RUNQUILL_PANEL_URL=%s\nRUNQUILL_PANEL_GITHUB_CLIENT_ID=%s\nRUNQUILL_PANEL_GITHUB_CLIENT_SECRET=%s\n", origin, app.ClientID, app.ClientSecret)
		}
		newApp = true
	default:
		return nil, err
	}
	if _, err := setupValues([]byte(pending.Env)); err != nil {
		return nil, err
	}
	if _, err := parseKey([]byte(pending.PEM)); err != nil {
		return nil, fmt.Errorf("parse GitHub App key: %w", err)
	}
	if newApp {
		data, err := json.Marshal(pending)
		if err != nil {
			return nil, err
		}
		if err := writeSetupFile(pendingPath, data); err != nil {
			return nil, fmt.Errorf("save setup recovery data: %w", err)
		}
	}
	if err := saveSetupFile(keyPath, []byte(pending.PEM)); err != nil {
		return nil, err
	}
	if err := saveSetupFile(envPath, []byte(pending.Env)); err != nil {
		return nil, err
	}
	if err := os.Remove(pendingPath); err != nil {
		return nil, fmt.Errorf("remove setup recovery data: %w", err)
	}
	return []byte(pending.Env), nil
}

func setupEnvironment(owner string, appID int64, image, tag string) string {
	env := fmt.Sprintf("%sRUNQUILL_OWNER=%s\nRUNQUILL_APP_ID=%d\nRUNQUILL_KEY_FILE=./%s\n", setupEnvHeader, owner, appID, setupKeyFile)
	if image != "" && setupImage.MatchString(image+":"+tag) {
		env += fmt.Sprintf("RUNQUILL_MANAGER_IMAGE=%s:%s\nRUNQUILL_RUNNER_IMAGE=%s-runner:%s\n", image, tag, image, tag)
	}
	return env
}

func setupValues(data []byte) (map[string]string, error) {
	content, generated := strings.CutPrefix(string(data), setupEnvHeader)
	if !generated {
		return nil, errors.New(".env already exists with manual configuration; use docker compose exec manager runquill doctor to check it")
	}
	values := make(map[string]string)
	for line := range strings.SplitSeq(content, "\n") {
		key, value, ok := strings.Cut(line, "=")
		if ok {
			values[strings.TrimSpace(key)] = strings.TrimSpace(value)
		}
	}
	id, err := strconv.ParseInt(values["RUNQUILL_APP_ID"], 10, 64)
	if err != nil || id <= 0 || !setupLogin.MatchString(values["RUNQUILL_OWNER"]) || values["RUNQUILL_KEY_FILE"] == "" {
		return nil, errors.New("generated .env has missing or invalid GitHub App settings")
	}
	return values, nil
}

func readSetupEnv(dir string) (map[string]string, error) {
	data, err := os.ReadFile(filepath.Join(dir, setupEnvFile))
	if err != nil {
		return nil, err
	}
	return setupValues(data)
}

// setupComposeFiles lists the Compose files a Docker deployment needs for these settings, in order.
func setupComposeFiles(values map[string]string, panel bool) []string {
	files := []string{"compose.yaml"}
	if panel {
		files = append(files, "compose.panel.yaml")
	}
	for host := range strings.SplitSeq(values["RUNQUILL_DOCKER_HOSTS"], ",") {
		host = strings.TrimSpace(host)
		switch {
		case strings.HasPrefix(host, "ssh://") && !slices.Contains(files, "compose.ssh.yaml"):
			files = append(files, "compose.ssh.yaml")
		case strings.HasPrefix(host, "agent://") && values["RUNQUILL_WORKER_AUTH_FILE"] != "" && !slices.Contains(files, "compose.worker.yaml"):
			files = append(files, "compose.worker.yaml")
		}
	}
	return files
}

// recordComposeFiles saves the Compose files in COMPOSE_FILE in .env, so a plain docker compose from the install
// directory keeps the overlays. Files already listed there stay, in their order, and the full list is returned.
func recordComposeFiles(dir string, files []string) ([]string, error) {
	values, err := readSetupEnv(dir)
	if err != nil {
		return nil, err
	}
	var recorded []string
	for file := range strings.SplitSeq(values["COMPOSE_FILE"], ":") {
		if file = strings.TrimSpace(file); file != "" && !slices.Contains(recorded, file) {
			recorded = append(recorded, file)
		}
	}
	for _, file := range files {
		if !slices.Contains(recorded, file) {
			recorded = append(recorded, file)
		}
	}
	return recorded, saveSetupEnv(dir, "COMPOSE_FILE", strings.Join(recorded, ":"))
}

// saveSetupEnv sets key in the generated .env, which must stay private and unchanged meanwhile.
func saveSetupEnv(dir, key, value string) error {
	path := filepath.Join(dir, setupEnvFile)
	original, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if _, err := setupValues(original); err != nil {
		return err
	}
	lines := strings.Split(strings.TrimSuffix(string(original), "\n"), "\n")
	set := false
	for i, line := range lines {
		if name, _, ok := strings.Cut(line, "="); ok && strings.TrimSpace(name) == key {
			lines[i], set = key+"="+value, true
		}
	}
	if !set {
		lines = append(lines, key+"="+value)
	}
	updated := []byte(strings.Join(lines, "\n") + "\n")
	if bytes.Equal(updated, original) {
		return nil
	}
	err = prepareSetupFile(path, updated, func(tmp string) error {
		info, err := os.Lstat(path)
		if err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 {
			return errors.New(".env changed during setup; rerun setup")
		}
		current, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(original, current) {
			return errors.New(".env changed during setup; rerun setup")
		}
		return os.Rename(tmp, path)
	})
	if err != nil {
		return fmt.Errorf("save %s in .env: %w", key, err)
	}
	return nil
}

func saveSetupFile(path string, data []byte) error {
	err := writeSetupFile(path, data)
	if errors.Is(err, os.ErrExist) {
		existing, readErr := os.ReadFile(path)
		if readErr == nil && bytes.Equal(existing, data) {
			info, statErr := os.Lstat(path)
			if statErr == nil && info.Mode().IsRegular() && info.Mode().Perm()&0077 == 0 {
				return nil
			}
		}
		return fmt.Errorf("%s already exists; setup kept it and preserved the new credentials in %s", path, setupPendingFile)
	}
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func writeSetupFile(path string, data []byte) error {
	return prepareSetupFile(path, data, func(tmp string) error { return os.Link(tmp, path) })
}

func prepareSetupFile(path string, data []byte, install func(string) error) error {
	file, err := os.CreateTemp(filepath.Dir(path), ".runquill-setup-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Sync(); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return install(file.Name())
}

func waitForSetupInstallation(ctx context.Context, out io.Writer, api *github) (githubInstallation, error) {
	ctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
	defer cancel()
	instructionsShown := false
	for {
		jwt, err := api.jwt(time.Now())
		if err != nil {
			return githubInstallation{}, err
		}
		inst, err := api.installation(ctx, jwt)
		if err == nil {
			err := errors.Join(inst.accessErrors(api.repositoryScope, api.runnerGroupID > 0))
			if err != nil {
				fmt.Fprintf(out, "Review the App installation at %s\n", api.installationURL(inst.ID))
				return inst, err
			}
			if api.runnerGroupID > 0 {
				_, err = api.inspectRunnerGroup(ctx, jwt, inst.ID)
			}
			return inst, err
		}
		if !githubNotFound(err) {
			return githubInstallation{}, err
		}
		if !instructionsShown {
			var app struct{ Slug string }
			if err := api.request(ctx, http.MethodGet, "/app", jwt, nil, &app); err != nil {
				return githubInstallation{}, err
			}
			if app.Slug == "" {
				return githubInstallation{}, errors.New("GitHub did not return an App slug")
			}
			installURL := "https://github.com/apps/" + url.PathEscape(app.Slug) + "/installations/new"
			if web := currentWizard(ctx); web != nil {
				web.setInstallURL(installURL, api.repositoryScope)
			}
			fmt.Fprintf(out, "Install the App on %s and choose %s:\n  %s\n", api.owner, repositoryScopeLabel(api.repositoryScope), installURL)
			if api.repositoryScope == scopeSelected {
				fmt.Fprintln(out, "Choose the private repositories that should run jobs on Runquill.")
			}
			fmt.Fprintln(out, "Waiting for installation. You can rerun setup to resume.")
			instructionsShown = true
		}
		timer := time.NewTimer(3 * time.Second)
		select {
		case <-ctx.Done():
			timer.Stop()
			return githubInstallation{}, ctx.Err()
		case <-timer.C:
		}
	}
}
